log = structlog.get_logger(__name__)
router = APIRouter()

_mint_guard = require_any_exact_scope("assess:mint", "assess:teacher")
_resend_guard = require_any_exact_scope("assess:teacher", "admin")

#: what a recipient-carrying field looks like, in a body key or a query name (REQ-082)
RECIPIENT_LIKE = re.compile(
    r"(recipient|address|e[-_]?mail|mail[-_]?to|^to$|^cc$|^bcc$|send[-_]?to|destinat)",
    re.I,
)

SERVE_HEADERS = {
    "Content-Type": "text/html; charset=utf-8",
    "Content-Security-Policy": "sandbox; default-src 'none'",
    "X-Content-Type-Options": "nosniff",
    "Cache-Control": "no-store",
    "Referrer-Policy": "no-referrer",
}


class MintBody(BaseModel):
    model_config = ConfigDict(extra="forbid")
    sub: int | None = Field(None, ge=1)
    actor_userid: int | None = Field(None, ge=1)


class ResendBody(BaseModel):
    model_config = ConfigDict(extra="forbid")
    actor_userid: int | None = Field(None, ge=1)


_TRANSCRIPT = text(
    "SELECT t.id, t.ciphertext, t.dek_wrapped, t.content_hash, t.filename, s.site_id, s.cmid, "
    "s.student_userid, s.courseid_hint FROM assess_transcripts t "
    "JOIN assess_sessions s ON s.id = t.session_id WHERE t.id = :t"
)
_INSERT_JTI = text(
    "INSERT INTO assess_transcript_download_tokens (jti_hash, transcript_id, subject_userid, "
    "expires_at, audience_role, site_id) VALUES (:h, :t, :u, :exp, :role, :site)"
)
_LIVE_JTI = text(
    "SELECT subject_userid, audience_role, site_id FROM assess_transcript_download_tokens "
    "WHERE jti_hash = :h AND consumed_at IS NULL AND expires_at > now() "
    "AND transcript_id = :t FOR UPDATE"
)
_CONSUME = text(
    "UPDATE assess_transcript_download_tokens SET consumed_at = now() WHERE jti_hash = :h"
)
_RESEND = text("SELECT assess_enqueue_resend(:t, :a, :gap)")


def download_tokens_of(request: Request) -> DownloadTokens:
    tokens = getattr(request.app.state, "assess_download_tokens", None)
    if tokens is not None:
        return tokens  # type: ignore[no-any-return]
    keys = getattr(request.app.state, "assess_keys", None) or {}
    signing = keys.get(SIGNING_SECRET)
    if not isinstance(signing, AssessKeyring):
        raise fail(assess_unavailable("token_signing_key"))
    settings = settings_of(request)
    tokens = DownloadTokens(
        keyring_from(signing),
        issuer=settings.token_issuer,
        ttl_s=settings.download_token_ttl_s,
    )
    request.app.state.assess_download_tokens = tokens
    return tokens


def transcript_key_of(request: Request) -> AssessKeyring:
    keys = getattr(request.app.state, "assess_keys", None) or {}
    ring = keys.get(store.KEYRING)
    if not isinstance(ring, AssessKeyring):
        raise fail(assess_unavailable("transcript_key"))
    return ring


async def verify_assess_token_download(request: Request) -> DownloadClaims:
    """The download token from the Authorization header only (never a query or a cookie)."""
    try:
        token = bearer_token(request)
    except Exception:
        raise fail(download_token_invalid()) from None
    try:
        return download_tokens_of(request).verify(token)
    except TokenError:
        raise fail(download_token_invalid()) from None


def _uuid(tid: str) -> UUID:
    try:
        return UUID(tid)
    except ValueError:
        raise fail(transcript_not_found()) from None


def _limit(request: Request, key: Any) -> None:
    """One budget per (transcript, role, requester) shared by the mint AND the download: a
    complete download costs two operations of ``VEKTRA_ASSESS_DOWNLOAD_RPM`` (at least 2)."""
    allowed, _ = limiter_of(request, "download").check(
        key, settings_of(request).download_rpm
    )
    if not allowed:
        raise fail(rate_limited(60, "download_rate"))


async def _site_of(conn: Any, key: ApiKeyInfo, purpose: str) -> UUID:
    site = (await conn.execute(SITE_OF_KEY, {"k": key.key_id, "p": purpose})).scalar()
    if site is None:
        raise fail(key_not_bound())
    return site  # type: ignore[no-any-return]


async def _grader_ok(
    conn: Any, row: Any, actor: int, settings: Any, *, grace_s: int = 0
) -> GraderCheck:
    return await check_fresh_grader(
        conn,
        site=row.site_id,
        student_userid=int(row.student_userid),
        cmid=int(row.cmid),
        actor_userid=actor,
        max_age_s=settings.teacher_gate_max_age_s + grace_s,
        courseid_hint=row.courseid_hint,
    )


@router.post("/transcripts/{tid}/download-token", status_code=201)
async def mint_download_token(
    tid: str, request: Request, key: ApiKeyInfo = Depends(_mint_guard)
) -> JSONResponse:
    body = await parse_body(request, MintBody)
    settings = settings_of(request)
    if (
        body.sub is not None
        and body.actor_userid is None
        and "assess:mint" in key.scopes
    ):
        role, requester, purpose = "owner", body.sub, "mint"
    elif (
        body.actor_userid is not None
        and body.sub is None
        and "assess:teacher" in key.scopes
    ):
        role, requester, purpose = "grader", body.actor_userid, "teacher"
    else:
        raise fail(bad_request("sub_or_actor_userid"))
    t = _uuid(tid)
    _limit(request, (t, role, requester))
    refused: Any = None
    async with engine_of(request).begin() as conn:
        site = await _site_of(conn, key, purpose)
        row = (await conn.execute(_TRANSCRIPT, {"t": t})).first()
        if row is None or row.site_id != site or row.ciphertext is None:
            raise fail(transcript_not_found())
        if role == "owner" and int(row.student_userid) != requester:
            await write_event(
                conn,
                AssessAuditEvent.OWNERSHIP_MISMATCH_REJECTED,
                actor="api",
                site_id=site,
                session_id=row.id,
                reason_code="transcript_download_token",
            )
            refused = _forbidden_owner()
        elif role == "grader":
            check = await _grader_ok(conn, row, requester, settings)
            if check is not GraderCheck.OK:
                refused = teacher_unverified()
        if refused is None:
            minted = download_tokens_of(request).mint(
                sub=requester,
                tid=t,
                site=site,
                role=role,  # type: ignore[arg-type]
            )
            await conn.execute(
                _INSERT_JTI,
                {
                    "h": minted.jti_hash,
                    "t": t,
                    "u": requester,
                    "exp": minted.expires_at,
                    "role": role,
                    "site": site,
                },
            )
            await write_event(
                conn,
                AssessAuditEvent.DOWNLOAD_TOKEN_MINT,
                actor="api",
                site_id=site,
                session_id=row.id,
                data={"role": role, "key_id": key.key_id},
            )
    if refused is not None:
        raise fail(
            refused
        )  # after commit: the refusal stays audited, the refresh queued
    return JSONResponse(
        status_code=201,
        content={"token": minted.token, "expires_in": minted.ttl_s},
        headers={"Cache-Control": "no-store"},
    )


def _forbidden_owner() -> ErrorResponse:
    """403 (ERR-AUTH-003): a student asking for another student's transcript (REQ-088)."""
    return ErrorResponse(
        category=ErrorCategory.PERMANENT,
        code=ERR_AUTH_003,
        message="This transcript belongs to another user.",
        remediation="A student can download only their own transcript.",
    )


@router.get("/transcripts/{tid}")
async def download_transcript(
    tid: str,
    request: Request,
    claims: DownloadClaims = Depends(verify_assess_token_download),
) -> Response:
    t = _uuid(tid)
    if claims.tid != t:
        raise fail(download_token_invalid())
    _limit(request, (t, claims.role, claims.sub))
    settings = settings_of(request)
    refused: Any = None
    async with engine_of(request).begin() as conn:
        # lock the live jti first (unknown, used, expired, another transcript's: 401) but
        # consume it only once the requester is authorized (review #7): a refusal that a retry
        # can cure (a stale grader list, refreshed meanwhile) must not burn the token
        live = (
            await conn.execute(_LIVE_JTI, {"h": jti_hash(claims.jti), "t": t})
        ).first()
        if (
            live is None
            or int(live.subject_userid) != claims.sub
            or live.audience_role != claims.role
            or live.site_id != claims.site
        ):
            raise fail(download_token_invalid())
        row = (await conn.execute(_TRANSCRIPT, {"t": t})).first()
        if row is None or row.ciphertext is None or row.site_id != claims.site:
            refused = transcript_not_found()
        elif claims.role == "owner" and int(row.student_userid) != claims.sub:
            await write_event(
                conn,
                AssessAuditEvent.OWNERSHIP_MISMATCH_REJECTED,
                actor="api",
                site_id=row.site_id,
                session_id=row.id,
                reason_code="transcript_download",
            )
            refused = _forbidden_owner()
        elif claims.role == "grader":
            # the list was fresh at mint: it stays acceptable for the token's own lifetime on
            # top of the bound; a grader the list no longer names is refused (fail closed)
            check = await _grader_ok(
                conn, row, claims.sub, settings, grace_s=settings.download_token_ttl_s
            )
            if check is not GraderCheck.OK:
                refused = teacher_unverified()
        if refused is None:
            await conn.execute(_CONSUME, {"h": jti_hash(claims.jti)})
        if refused is None and row is not None:
            filename = str(row.filename)
            try:
                body = store.open_verified(
                    transcript_key_of(request),
                    t,
                    bytes(row.ciphertext),
                    bytes(row.dek_wrapped),
                    str(row.content_hash),
                )
            except store.TranscriptIntegrityError as exc:
                log.error(
                    "assess.transcript.alert",
                    alert="integrity_mismatch_at_download",
                    transcript_id=str(t),
                    reason=str(exc),
                )
                refused = transcript_integrity()
            else:
                await write_event(
                    conn,
                    AssessAuditEvent.STUDENT_DOWNLOAD
                    if claims.role == "owner"
                    else AssessAuditEvent.TEACHER_DOWNLOAD,
                    actor="api",
                    site_id=row.site_id,
                    session_id=row.id,
                    data={"bytes": len(body)},
                )
    if refused is not None:
        # an integrity refusal keeps the token consumed; an authorization refusal left it live
        raise fail(refused)
    return Response(
        content=body,
        media_type=None,
        headers={
            **SERVE_HEADERS,
            "Content-Disposition": content_disposition(filename),
        },
    )


@router.post("/transcripts/{tid}/resend", status_code=202)
async def resend_transcript(
    tid: str, request: Request, key: ApiKeyInfo = Depends(_resend_guard)
) -> JSONResponse:
    _refuse_query(request)
    # one capped read (review #5): the recipient scan and the model see the same object
    doc = json_object(await read_capped_body(request))
    if any(RECIPIENT_LIKE.search(k) for k in _all_keys(doc)):
        raise fail(resend_recipient_forbidden())
    body = validate_body(doc, ResendBody)
    settings = settings_of(request)
    t = _uuid(tid)
    allowed, _ = limiter_of(request, "resend").check(
        ("resend", key.key_id), settings.resend_rpm
    )
    if not allowed:
        raise fail(rate_limited(60, "resend_rate"))
    teacher = "assess:teacher" in key.scopes and "admin" not in key.scopes
    if teacher and body.actor_userid is None:
        raise fail(bad_request("actor_userid"))
    refused: Any = None
    async with engine_of(request).begin() as conn:
        row = (await conn.execute(_TRANSCRIPT, {"t": t})).first()
        if teacher:
            site = await _site_of(conn, key, "teacher")
            if row is None or row.site_id != site:
                raise fail(transcript_not_found())
            check = await _grader_ok(conn, row, int(body.actor_userid or 0), settings)
            if check is not GraderCheck.OK:
                refused = teacher_unverified()
            actor = f"grader:{body.actor_userid}"
        else:
            if row is None:
                raise fail(transcript_not_found())
            actor = f"operator:{key.key_id}"[:64]
        if refused is None:
            gap = settings.resend_min_interval_s
            got = await conn.execute(_RESEND, {"t": t, "a": actor, "gap": gap})
            new_round = int(got.scalar() or 0)
            if new_round == 0:
                # not generated, or never had a recipient
                raise fail(transcript_not_found())
            if new_round == -1:
                # a round less than the minimum interval ago (review #6): each mails up to 3
                refused = rate_limited(max(1, gap), "resend_interval")
            else:
                await enqueue_job(
                    conn,
                    JobKind.TRANSCRIPT_DELIVER,
                    {"transcript_id": str(t)},
                    dedupe_key=f"transcript_deliver:{t}:{new_round}",
                )
    if refused is not None:
        raise fail(refused)
    return JSONResponse(
        status_code=202,
        content={"transcript_id": str(t), "round": new_round},
        headers={"Cache-Control": "no-store"},
    )


def _refuse_query(request: Request) -> None:
    """REQ-082: a resend takes NO query parameter. A recipient-like name is the explicit
    ``ERR-ASSESS-019``, anything else a plain 400. The names are only matched, never read as a
    value or a credential (the static credential test allows this function and nothing else)."""
    names = list(request.query_params)
    if any(RECIPIENT_LIKE.search(name) for name in names):
        raise fail(resend_recipient_forbidden())
    if names:
        raise fail(bad_request("query_not_allowed"))


def _all_keys(doc: Any) -> list[str]:
    """Every key of a decoded JSON body, at any depth, before the model sees it (``extra=
    "forbid"`` would report only the first one, as a generic 400). Iterative: no recursion
    limit to hit, whatever the nesting the decoder accepted."""
    keys: list[str] = []
    stack = [doc]
    while stack:
        node = stack.pop()
        if isinstance(node, dict):
            keys.extend(str(k) for k in node)
            stack.extend(node.values())
        elif isinstance(node, list):
            stack.extend(node)
    return keys
