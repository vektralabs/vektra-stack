"""Assess session lifecycle schema (plan assess-session-lifecycle, PR 8a).

- ``assess_token_jti``: one row per minted pre-session token. It is both the single-use store
  (Start and resume set ``consumed_at``) and the mint-to-Start correlation record: a Start whose
  jti has no row, a row minted by a key that is no longer the site's mint key, or a consumed row
  is refused (ARCH-067). The done-job cleanup tick deletes rows a day past ``expires_at``.
  ``assess_consumed_jtis`` (revision 0013) stays for the transcript download path.
- ``assess_jobs``: the ``preflight`` kind (the worker pre-flight, bound with this revision).
- ``assess_start_attempts``: outcome ``requested`` (written by the API at Start; the worker adds
  ``committed`` / ``rolled_back`` rows, so no role needs UPDATE) and the ``session_id`` it
  concerns (no FK: a rolled-back session row is deleted, its attempts stay as evidence).
- ``assess_sessions``: ``courseid_hint`` (the plugin's course id, re-resolved by the worker),
  ``duration_s`` (cap + extra time frozen at commit), ``frozen_policy`` (the content-free BR-011
  disclosure decision the API needs to assemble the bundle on every turn, BR-008) and
  ``preflight_started_at`` (a STARTING session counts against admission K once its pre-flight
  runs).
- ``assess_activity_config.cap_minutes``: the BR-013 session cap (5-120). NULL means the activity
  is not configured, and a Start is rolled back (plan 11 owns the teacher form that writes it).

Grants: the whole matrix is re-rendered from ``vektra_assess.db.grants`` (the API reads and
consumes token rows and reads Start attempts; the worker reads and deletes token rows).

Revision ID: 0022
Revises: 0021
"""

